import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';

const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const finale=readFileSync(new URL('../story-finale.js',import.meta.url),'utf8');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
const narrative=scripts.find(x=>x.includes('root.Narrative=Object.freeze'));
const persistence=scripts.find(x=>x.includes('root.Save={KEY,fresh,clean,load,save,reset}'));
assert.ok(narrative&&persistence,'Narrative and save components exist');
const ctx={window:{Lumina:{}}};
vm.runInNewContext(narrative,ctx);
vm.runInNewContext(persistence,ctx);
const {Narrative:N,Save}=ctx.window.Lumina;
assert.equal(Object.keys(N.BEATS).length,8);
assert.equal(N.ARCHIVE_LOGS.length,3);
assert.equal(N.FINAL_CASES.length,3);
assert.ok(N.BEATS.nix.join(' ').includes('eco'),'Restoring NIX explains the urban echo');
assert.ok(N.BEATS.guardian.join(' ').includes('Autorización'),'Centinela authorizes passage');
assert.ok(N.BEATS.tower.join(' ').includes('REPETIR'),'Tower connects loops to final routing');
const base={metroRelays:[true,true],guardianDefeated:false,beacon:false,completed:false};
assert.equal(N.canBoard(base),false,'Train must not bypass the archive guardian');
assert.equal(N.canBoard({...base,guardianDefeated:true}),true);
assert.equal(N.canBoard({...base,metroRelays:[true,false],guardianDefeated:true}),false);
assert.equal(N.canBoard({...base,beacon:true}),true,'Older players at the lighthouse may still travel');
assert.equal(N.canBoard({...base,completed:true}),true,'Older completed saves retain northern passage');
const valid=N.evaluateFinal('AND',true);
assert.equal(valid.passed,true);
assert.equal(valid.cases.filter(x=>x.correct).length,3);
assert.deepEqual(Array.from(valid.cases,x=>x.actual),['TRANSMITIR','AISLAR','AISLAR']);
assert.equal(N.evaluateFinal('OR',true).passed,false,'OR would spread an unsafe signal');
assert.equal(N.evaluateFinal('AND',false).passed,false,'Reading alarm without NO must fail');
assert.equal(N.evaluateFinal('OR',false).passed,false);
assert.equal(N.evaluateFinal('X',true).valid,false);
const fresh=Save.fresh();
assert.equal(fresh.signalBalanced,false);
assert.equal(Object.keys(fresh.storyBeats).length,0);
const updated=Save.clean({...fresh,signalBalanced:true,storyBeats:{metro:true,archive:true,garbage:true}});
assert.equal(updated.signalBalanced,true);
assert.equal(updated.storyBeats.metro,true);
assert.equal(updated.storyBeats.archive,true);
assert.equal(updated.storyBeats.garbage,undefined,'Foreign keys never enter save');
const past=Save.clean({...fresh,signalBalanced:undefined,storyBeats:undefined,cityCompleted:true});
assert.equal(past.cityCompleted,true);
assert.equal(past.signalBalanced,false,'Legacy save migrates safely');
assert.ok(html.includes('src="./story-finale.js"'),'Finale module loaded before game boot');
assert.ok(finale.includes('Game.prototype.openRouting='));
assert.ok(finale.includes('Game.prototype.runRouting='));
assert.ok(finale.includes('this.save.signalBalanced=true;this.persist();'),'Final rule persists on victory');
assert.ok(finale.includes('if(!this.save.signalBalanced){this.openRouting();return;}'),'Ending gated on safe transmission');
console.log('Story PASS: archive gate, coherent lore beats, signal routing, saves and finale integration');
